# frozen_string_literal: true

require 'test_helper'
require_relative '../../app/services/export_standard_template_service'
require_relative '../../app/services/payroll_import_service'

class PayrollImportServiceTest < ActiveSupport::TestCase
  test 'parses the standard template generated by ExportStandardTemplateService' do
    company = Company.first || Company.new(name: 'Demo')
    tmp_path = ExportStandardTemplateService.new(company).call
    file = File.open(tmp_path)

    service = PayrollImportService.new(company, file)
    result = service.call

    assert result[:rows].is_a?(Array)
    assert result[:rows].length >= 1
    assert result[:rates].is_a?(Hash)
  ensure
    file.close if file
  end
end
